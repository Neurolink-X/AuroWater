-- AuroTap Web Push: consented devices + bounded, recoverable delivery metadata.
-- No duplicate order payloads, no client-accessible subscription keys or queue.
CREATE TABLE IF NOT EXISTS public.web_push_preferences (
  user_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
  push_enabled boolean NOT NULL DEFAULT false,
  marketing_enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.web_push_subscriptions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE CHECK (char_length(endpoint) BETWEEN 30 AND 2048),
  p256dh text NOT NULL CHECK (char_length(p256dh) BETWEEN 40 AND 200),
  auth_secret text NOT NULL CHECK (char_length(auth_secret) BETWEEN 12 AND 100),
  enabled boolean NOT NULL DEFAULT true,
  failure_count integer NOT NULL DEFAULT 0 CHECK (failure_count BETWEEN 0 AND 100),
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_web_push_active_user
  ON public.web_push_subscriptions(user_id) WHERE enabled = true;

CREATE TABLE IF NOT EXISTS public.web_push_deliveries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id uuid NOT NULL REFERENCES public.notifications(id) ON DELETE CASCADE,
  subscription_id uuid NOT NULL REFERENCES public.web_push_subscriptions(id) ON DELETE CASCADE,
  state text NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending','leased','delivered','failed','revoked')),
  attempts smallint NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 12),
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  leased_until timestamptz,
  last_error_code text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(notification_id, subscription_id)
);
CREATE INDEX IF NOT EXISTS idx_web_push_due
  ON public.web_push_deliveries(next_attempt_at, id)
  WHERE state IN ('pending', 'leased');

ALTER TABLE public.web_push_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.web_push_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.web_push_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.web_push_preferences, public.web_push_subscriptions,
  public.web_push_deliveries FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.web_push_preferences, public.web_push_subscriptions,
  public.web_push_deliveries TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.web_push_deliveries_id_seq TO service_role;

-- Writes to the existing user inbox stay authoritative. The outbox stores
-- foreign keys + delivery state, not repeated notification text or order data.
CREATE OR REPLACE FUNCTION private.enqueue_user_web_push()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog
AS $func$
BEGIN
  INSERT INTO public.web_push_deliveries(notification_id, subscription_id)
  SELECT NEW.id, sub.id
  FROM public.web_push_preferences pref
  JOIN public.web_push_subscriptions sub
    ON sub.user_id = pref.user_id AND sub.enabled = true
  WHERE pref.user_id = NEW.user_id
    AND pref.push_enabled
    AND (NEW.type <> 'promo' OR pref.marketing_enabled)
  ON CONFLICT (notification_id, subscription_id) DO NOTHING;
  RETURN NEW;
END;
$func$;
REVOKE ALL ON FUNCTION private.enqueue_user_web_push() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS enqueue_user_web_push ON public.notifications;
CREATE TRIGGER enqueue_user_web_push
  AFTER INSERT ON public.notifications
  FOR EACH ROW EXECUTE FUNCTION private.enqueue_user_web_push();

-- The database lease provides at-most-one active worker per delivery. A lease
-- expires so a serverless termination cannot permanently strand the job.
CREATE OR REPLACE FUNCTION public.claim_web_push_deliveries(p_limit integer DEFAULT 8)
RETURNS SETOF public.web_push_deliveries
LANGUAGE sql
SECURITY INVOKER
SET search_path = pg_catalog
AS $func$
  WITH candidates AS (
    SELECT id
    FROM public.web_push_deliveries
    WHERE (state = 'pending' AND next_attempt_at <= clock_timestamp())
       OR (state = 'leased' AND leased_until < clock_timestamp())
    ORDER BY next_attempt_at, id
    FOR UPDATE SKIP LOCKED
    LIMIT LEAST(GREATEST(p_limit, 1), 12)
  )
  UPDATE public.web_push_deliveries d
  SET state = 'leased', leased_until = clock_timestamp() + interval '60 seconds',
      updated_at = clock_timestamp()
  FROM candidates c WHERE d.id = c.id
  RETURNING d.*;
$func$;
REVOKE ALL ON FUNCTION public.claim_web_push_deliveries(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_web_push_deliveries(integer) TO service_role;

-- Delete only *delivery transport metadata*, never unread inbox entries.
CREATE OR REPLACE FUNCTION private.prune_web_push_delivery_history()
RETURNS integer
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog
AS $func$
DECLARE v_count integer;
BEGIN
  WITH old_rows AS (
    SELECT id FROM public.web_push_deliveries
    WHERE (state IN ('delivered','revoked') AND updated_at < now()-interval '7 days')
       OR (state = 'failed' AND updated_at < now()-interval '30 days')
    ORDER BY updated_at, id LIMIT 300
  )
  DELETE FROM public.web_push_deliveries d USING old_rows r WHERE d.id = r.id;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$func$;
REVOKE ALL ON FUNCTION private.prune_web_push_delivery_history() FROM PUBLIC, anon, authenticated;
SELECT cron.schedule(
  'aurotap-web-push-queue-retention',
  '24 3 * * *',
  'SELECT private.prune_web_push_delivery_history()'
);
